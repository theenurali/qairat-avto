const NAIVE_CODE = `def naive_search(text, pattern):
    n, m = len(text), len(pattern)
    result = []
    for s in range(n - m + 1):          # каждое возможное начало окна
        if text[s:s + m] == pattern:    # сравнение до m символов
            result.append(s)
    return result`;

const RK_CODE = `def rabin_karp(text, pattern, d=256, q=101):
    n, m = len(text), len(pattern)
    if m == 0 or m > n:
        return []
    h = pow(d, m - 1, q)            # d^(m-1) mod q — «вес» старшего символа
    p = 0                           # hash(pattern)
    t = 0                           # hash(текущего окна текста)
    for i in range(m):              # оба хеша считаем схемой Горнера
        p = (d * p + ord(pattern[i])) % q
        t = (d * t + ord(text[i])) % q
    result = []
    for s in range(n - m + 1):      # s — начало окна
        if p == t:                  # хеши совпали → проверяем символы
            if text[s:s + m] == pattern:
                result.append(s)    # настоящее совпадение (match)
            # иначе: spurious hit — хеши равны, строки разные
        if s < n - m:               # сдвигаем окно на 1 вправо (rolling hash)
            t = (d * (t - ord(text[s]) * h) + ord(text[s + m])) % q
    return result`;

const MULTI_CODE = `def rabin_karp_multi(text, patterns, d=256, q=1_000_003):
    m = len(patterns[0])                     # все образцы одной длины
    targets = {}
    for pat in patterns:                     # hash → список образцов
        targets.setdefault(poly_hash(pat, d, q), []).append(pat)
    found = []
    for s, t in rolling_hashes(text, m, d, q):
        for pat in targets.get(t, []):       # O(1) проверка по словарю
            if text[s:s + m] == pat:
                found.append((s, pat))
    return found`;

